"""Finite-p (p-leader) extension: regression guard for p=infinity, unit
tests for the new validity checks, and a cross-check against MULTIFRACS's
own DxPx2d.m finite-p leader construction.

The cross-check reference (`handoff/plbmf_crosscheck/
multifracs_pleader_reference.json`) was generated by running MULTIFRACS's
DxPx2d.m directly (MATLAB R2026a, the toolbox at
`multifracs/MF_BS_tool_webrelease/`) on the exact field `_reference_field()`
builds below, with `param_est.plead_corr = 0` -- MULTIFRACS's own
NLcorrPL2d.m nonlinearity correction disabled, since it is a separate,
additional post-processing step (multiplying the raw leader by a scale-
dependent correction factor derived from fractional integration/gamint)
that is explicitly out of scope for this extension (leader construction
only) -- see leaders.py's module docstring. Comparing against MULTIFRACS's
*corrected* output would not be apples-to-apples with what this extension
implements.
"""

import json
import os

import numpy as np
import pytest

from mfleaders._dwt2 import leaders_2d, wavelet_transform_2d, combine_orientations_p
from mfleaders.leaders import compute_leaders

from synthetic import fbm2d_spectral

_REFERENCE_PATH = os.path.join(
    os.path.dirname(__file__), '..', 'handoff', 'plbmf_crosscheck',
    'multifracs_pleader_reference.json',
)


def _reference_field():
    """The exact field the MULTIFRACS reference (see module docstring) was
    computed from: fbm2d_spectral(n=128, H=0.6, default_rng(42)), shifted
    to strictly positive (matching what was fed to DxPx2d.m)."""
    rng = np.random.default_rng(42)
    field = fbm2d_spectral(128, 0.6, rng)
    return field - field.min() + 0.1


def _crop_to_finite_bbox(arr):
    finite = np.isfinite(arr)
    rows = np.where(finite.any(axis=1))[0]
    cols = np.where(finite.any(axis=0))[0]
    return arr[rows.min():rows.max() + 1, cols.min():cols.max() + 1]


# ---------------------------------------------------------------------------
# Regression guard: p=infinity must be byte-identical to pre-extension
# behavior. These don't need MULTIFRACS at all -- just compare compute_leaders
# with p left at its default vs p passed explicitly, and vs the existing
# certified pipeline.
# ---------------------------------------------------------------------------

def test_p_inf_default_matches_explicit_p_inf():
    field = _reference_field()
    coeffs = wavelet_transform_2d(field, border='multifracs')
    from mfleaders._dwt2 import combine_orientations
    mag = combine_orientations(coeffs)

    default = compute_leaders(mag, dim=2)
    explicit = compute_leaders(mag, dim=2, p=np.inf)

    for j in default:
        np.testing.assert_array_equal(default[j], explicit[j])


def test_p_inf_leaders_2d_unchanged_by_finite_p_addition():
    """leaders_2d(image) (p=inf, default) must be bit-identical to calling
    it with p=np.inf explicitly -- the finite-p code path must never be
    touched when p is infinite."""
    field = _reference_field()
    default = leaders_2d(field)
    explicit = leaders_2d(field, p=np.inf)
    for j in default:
        np.testing.assert_array_equal(default[j], explicit[j])


# ---------------------------------------------------------------------------
# p-validity and parameter-handling unit tests.
# ---------------------------------------------------------------------------

def test_nonpositive_p_raises():
    field = _reference_field()
    coeffs = wavelet_transform_2d(field, border='multifracs')
    mag_p = combine_orientations_p(coeffs, 2.0)
    with pytest.raises(ValueError):
        compute_leaders(mag_p, dim=2, p=0.0, pre_combined_power=True)
    with pytest.raises(ValueError):
        compute_leaders(mag_p, dim=2, p=-1.0, pre_combined_power=True)


def test_finite_p_with_pymultifracs_cone_raises_not_implemented():
    coeffs = {1: np.abs(np.random.default_rng(0).standard_normal((16,)))}
    with pytest.raises(NotImplementedError):
        compute_leaders(coeffs, dim=1, p=2.0, cone='pymultifracs')


def test_finite_p_with_explicit_weight_warns_and_ignores_it():
    field = _reference_field()
    coeffs = wavelet_transform_2d(field, border='multifracs')
    mag_p = combine_orientations_p(coeffs, 2.0)
    with pytest.warns(RuntimeWarning, match='weight'):
        with_weight = compute_leaders(mag_p, dim=2, p=2.0, weight=0.5,
                                       pre_combined_power=True)
    without_weight = compute_leaders(mag_p, dim=2, p=2.0,
                                      pre_combined_power=True)
    for j in with_weight:
        np.testing.assert_array_equal(with_weight[j], without_weight[j])


def test_p_validity_warning_fires_on_field_with_many_exact_zeros():
    """Mirrors MULTIFRACS's own NLcorrPL2d.m check (zp <= 0 -> warn). A
    field that's mostly exact zero (like a very sparse mask) at large p
    should trip it; a smooth, everywhere-positive field at small p should
    not.
    """
    rng = np.random.default_rng(0)
    sparse = np.zeros((64, 64))
    sparse[::8, ::8] = rng.standard_normal((8, 8)) ** 2 + 1.0
    coeffs = wavelet_transform_2d(sparse, border='multifracs')
    mag_p = combine_orientations_p(coeffs, 8.0)
    with pytest.warns(RuntimeWarning, match='p-leader validity'):
        compute_leaders(mag_p, dim=2, p=8.0, pre_combined_power=True)


def test_p_validity_warning_does_not_fire_on_well_behaved_field():
    field = _reference_field()
    coeffs = wavelet_transform_2d(field, border='multifracs')
    mag_p = combine_orientations_p(coeffs, 1.0)
    with warnings_as_errors_except_unrelated():
        compute_leaders(mag_p, dim=2, p=1.0, pre_combined_power=True)


class warnings_as_errors_except_unrelated:
    """Context manager: fail the test if a p-leader-validity RuntimeWarning
    fires (would mean the well-behaved reference field spuriously trips the
    check); any other warning is allowed through."""

    def __enter__(self):
        import warnings
        self._cm = warnings.catch_warnings(record=True)
        self._records = self._cm.__enter__()
        warnings.simplefilter('always')
        return self

    def __exit__(self, *exc):
        for w in self._records:
            assert 'p-leader validity' not in str(w.message), str(w.message)
        self._cm.__exit__(*exc)
        return False


# ---------------------------------------------------------------------------
# Cross-check against MULTIFRACS's own DxPx2d.m finite-p leaders.
# ---------------------------------------------------------------------------

@pytest.mark.skipif(not os.path.exists(_REFERENCE_PATH),
                     reason="multifracs_pleader_reference.json not present")
@pytest.mark.parametrize("p_key,p", [("p1", 1.0), ("p2", 2.0)])
def test_finite_p_leaders_match_multifracs_dxpx2d(p_key, p):
    with open(_REFERENCE_PATH) as f:
        ref = json.load(f)

    field = _reference_field()
    py_leaders = leaders_2d(field, p=p)

    entry = ref['leaders_by_p'][p_key]
    assert entry['p'] == p

    for j_str, scale_ref in entry['scales'].items():
        j = int(j_str)
        matlab_leader = np.array(scale_ref['values']).reshape(scale_ref['shape'])
        py_cropped = _crop_to_finite_bbox(py_leaders[j])

        assert py_cropped.shape == matlab_leader.shape, (
            f"p={p}, scale {j}: shape mismatch "
            f"py={py_cropped.shape} matlab={matlab_leader.shape}"
        )
        max_abs_diff = np.max(np.abs(py_cropped - matlab_leader))
        max_rel_diff = np.max(
            np.abs(py_cropped - matlab_leader) / np.maximum(np.abs(matlab_leader), 1e-300)
        )
        assert max_rel_diff < 1e-6, (
            f"p={p}, scale {j}: max_abs_diff={max_abs_diff:.3e} "
            f"max_rel_diff={max_rel_diff:.3e} (tolerance 1e-6)"
        )
